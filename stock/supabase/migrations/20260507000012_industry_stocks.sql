-- 產業熱門股表 + seed
-- 10 個產業 × 10 個股,由開發者依台股市場知識選的高關注度個股
-- 後續可用 SQL 直接增刪 row 維護

create table public.industry_stocks (
  id bigserial primary key,
  industry text not null,
  symbol text not null,
  name text,
  display_order integer not null default 0,
  added_at timestamptz not null default now(),
  unique (industry, symbol)
);
create index idx_industry_stocks_industry on public.industry_stocks (industry, display_order);
alter table public.industry_stocks enable row level security;

